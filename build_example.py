"""Regenerate the browser-only example from the real roster and synthetic profile."""
import asyncio
import json
from datetime import datetime, timezone
from pathlib import Path

from app.agent import run_agent
from app.models import PlanRequest


async def main():
    trace = []

    async def emit(stage, message, data):
        trace.append({"type": "event", "stage": stage, "message": message, "data": data})

    req = PlanRequest(
        goal="I want to become a product or data analyst. Help me build skills in data science, programming, statistics, and human-centered digital products.",
        demo=True, roster="SP27", career="UG", campus="MAIN",
        min_credits=12, max_credits=16, course_count=4, earliest=540, latest=1080,
        completed=[{"code": code, "grade": grade, "status": "completed"}
                   for code, grade in [("CS 1110", "A"), ("MATH 1110", "B+"),
                                       ("MATH 1710", "A-"), ("ECON 1110", "B")]],
    )
    result = await run_agent(req, None, emit)
    assert result["families"] and result["usage"]["calls"] == 0
    result.pop("timings_ms", None)
    result["data_mode"] = "Static example: precomputed Python solver output using the official Cornell snapshot and deterministic sample scoring. No live LLM calls."
    result["example_generated_at"] = datetime.now(timezone.utc).isoformat()
    payload = json.dumps({"result": result, "trace": trace}, ensure_ascii=False, separators=(",", ":"))
    path = Path(__file__).parent / "static" / "example.js"
    path.write_text("// Generated by build_example.py; public roster data and a fictional student profile.\nconst COURSE_COMPASS_EXAMPLE = " + payload + ";\n")
    print(f"Saved {len(result['families'])} families / {sum(len(f['variants']) for f in result['families'])} variants to {path.name} ({path.stat().st_size:,} bytes).")


if __name__ == "__main__":
    asyncio.run(main())
